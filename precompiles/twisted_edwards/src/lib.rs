//! Twisted-Edwards elliptic-curve point-addition precompile for the ZisK zkVM.
//!
//! Proves complete point addition on the curve `a*x^2 + y^2 = 1 + d*x^2*y^2` for every curve
//! instantiated in the `TwistedEdwards` AIR, one operation per curve:
//!
//! * `babyjubjub_add` — circom/circomlib BabyJubJub, `a = 168700`, `d = 168696`, over the BN254
//!   *scalar* field `Fr` (`p = 0x30644E72E131A029B85045B68181585D2833E84879B9709143E1F593F0000001`).
//! * `ed25519_add` — RFC 8032 edwards25519, `a = -1`, `d = -121665/121666`, over
//!   `p = 2^255 - 19`.
//!
//! Points are affine `(x, y)`, each a 256-bit field element laid out as `[u64; 4]`; a point is
//! `[u64; 8]` (`x || y`), no compression.
//!
//! The addition law is complete (the same formula doubles, with no exceptional cases for valid
//! points):
//!
//! ```text
//! tau = x1*x2*y1*y2
//! x3  = (x1*y2 + y1*x2) / (1 + d*tau)
//! y3  = (y1*y2 - a*x1*x2) / (1 - d*tau)
//! ```
//!
//! # Why a dedicated AIR
//!
//! The shared `arith_eq` AIR is hard-capped at `MAX_CEQS = 3` / `QS = 3` concurrent equations.
//! The complete addition decomposes into 7 flat degree-<=2 polynomial identities (with five
//! scratch values `A, B, Nx, T, DT`), so it needs its own AIR rather than widening `arith_eq` —
//! which would raise proving cost for every existing `arith_eq` op (secp256k1, bn254, arith256).
//! The constraint model (16x16-bit chunks, 22-bit quotient/carry sizing, carry-chain closure
//! forcing the integer LHS to zero, and a per-chunk LT-table lookup pinning the outputs `< p`
//! alias-free) mirrors `arith_eq` exactly. Every curve shares the same columns and the same 7
//! equation slots, each gated by its own clk0 selector.
//!
//! # Soundness of the multiply-through output equations
//!
//! `x3`/`y3` are constrained in multiply-through form (`x3*(1+DT) = Nx`, `y3*(1-DT) = B - a*A`),
//! not via an explicit inverse gate like circomlib's `BabyAdd`. This is sound *because of the
//! curve parameters*: an output coordinate could only become free if a denominator `1 +- d*tau`
//! were zero while the corresponding numerator is also zero, and that configuration forces a
//! square root of `1/d` (for `x3`) or `1/(a*d)` (for `y3`). For every curve of the AIR both `d`
//! and `a*d` are quadratic non-residues mod `p` (asserted at PIL compile time), so no such inputs
//! exist, and the outputs are uniquely pinned. See the soundness note in `pil/twisted_edwards.pil`
//! for the full argument.
//!
//! # Module layout
//!
//! `twisted_edwards` is the state-machine core that fills the trace; `executors` computes the
//! field values, quotients and carries for a given [`TwistedEdwardsCurve`]; `mem_inputs` produces
//! the memory bus inputs; and `equations` holds the generated per-equation chunk polynomials,
//! regenerated by the `twisted_edwards_generator` binary (which reuses the `arith_eq` equation
//! generator). Manager / planner / instance / collector / counter shells come from
//! `zisk_precompile!`.
