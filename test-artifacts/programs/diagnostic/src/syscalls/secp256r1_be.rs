use ziskos::syscalls::*;

#[inline]
fn be4(a: [u64; 4]) -> [u64; 4] {
    [a[3].swap_bytes(), a[2].swap_bytes(), a[1].swap_bytes(), a[0].swap_bytes()]
}

pub fn diagnostic_secp256r1_be() {
    //////////////
    // Secp256r1Be Add Tests
    //////////////

    let mut p1 = SyscallPoint256 { x: [0, 0, 0, 0], y: [0, 0, 0, 0] };
    let p2 = SyscallPoint256 { x: [0, 0, 0, 0], y: [0, 0, 0, 0] };
    let mut params = SyscallSecp256r1AddParams { p1: &mut p1, p2: &p2 };

    let mut p1 = SyscallPoint256 {
        x: be4([
            16892139108441294589,
            2268514658981987564,
            16660966552361989397,
            8255624973293160409,
        ]),
        y: be4([
            12156787655537736728,
            12309038971325631416,
            14142088599640780838,
            10821218243387965909,
        ]),
    };
    let p2 = SyscallPoint256 {
        x: be4([
            16973845534452172152,
            13329017265419983731,
            4846551096244594695,
            16860145613434125549,
        ]),
        y: be4([
            6998788062897069940,
            14598273846219819996,
            11018065767077453577,
            15562535120954986242,
        ]),
    };
    params.p1 = &mut p1;
    params.p2 = &p2;
    syscall_secp256r1_add_be(&mut params);
    let p3 = SyscallPoint256 {
        x: be4([
            8464213199400360201,
            16517470414429219854,
            12373804499568192784,
            15953995638987652322,
        ]),
        y: be4([
            9425804923940431393,
            10358190992697745803,
            12208774769574787222,
            13970165524275089144,
        ]),
    };
    assert_eq!(params.p1.x, p3.x);
    assert_eq!(params.p1.y, p3.y);

    //////////////
    // Secp256r1Be Dbl Tests
    //////////////

    let mut p1 = SyscallPoint256 {
        x: be4([
            14589376466333626517,
            2958991646043105326,
            18026143254603003885,
            13357802854741894370,
        ]),
        y: be4([
            12670586254094269143,
            17744077126965479691,
            406637352836607580,
            2297867320012306620,
        ]),
    };
    syscall_secp256r1_dbl_be(&mut p1);
    let p3 = SyscallPoint256 {
        x: be4([
            16423661298614043999,
            7723780046353944935,
            5703309917023540161,
            2894873586423611991,
        ]),
        y: be4([
            14644712083338957576,
            1531257909946502656,
            6507004370024078625,
            4022521928009034802,
        ]),
    };
    assert_eq!(p1.x, p3.x);
    assert_eq!(p1.y, p3.y);
}
