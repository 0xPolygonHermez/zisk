use ziskos::syscalls::*;

#[inline]
fn be4(a: [u64; 4]) -> [u64; 4] {
    [a[3].swap_bytes(), a[2].swap_bytes(), a[1].swap_bytes(), a[0].swap_bytes()]
}

pub fn diagnostic_secp256k1_be() {
    //////////////
    // Secp256k1Be Add Tests
    //////////////

    let mut p1 = SyscallPoint256 { x: [0, 0, 0, 0], y: [0, 0, 0, 0] };
    let p2 = SyscallPoint256 { x: [0, 0, 0, 0], y: [0, 0, 0, 0] };
    let mut params = SyscallSecp256k1AddParams { p1: &mut p1, p2: &p2 };

    let mut p1 = SyscallPoint256 {
        x: be4([545887436851369351, 6828787688065214038, 3784847408168804653, 5801960250918850699]),
        y: be4([7960650550461533833, 6752854485708698976, 7033117147444881223, 3794673124853157169]),
    };
    let p2 = SyscallPoint256 {
        x: be4([545887435628795271, 6828787688065214038, 3784847408168804653, 5801960250918850699]),
        y: be4([
            17120705537189757149,
            10411841749873587876,
            3281661694091576154,
            5012240766734575141,
        ]),
    };
    params.p1 = &mut p1;
    params.p2 = &p2;
    syscall_secp256k1_add_be(&mut params);
    let p3 = SyscallPoint256 {
        x: be4([
            16302535435195808843,
            8543364680260097415,
            14908508942232280741,
            15497036330728249576,
        ]),
        y: be4([6141349181170948100, 1750840565155776462, 5517384897023788690, 9517308371755837438]),
    };
    assert_eq!(params.p1.x, p3.x);
    assert_eq!(params.p1.y, p3.y);

    //////////////
    // Secp256k1Be Dbl Tests
    //////////////

    let mut p1 = SyscallPoint256 {
        x: be4([545887436851369351, 6828787688065214038, 3784847408168804653, 5801960250918850699]),
        y: be4([7960650550461533833, 6752854485708698976, 7033117147444881223, 3794673124853157169]),
    };
    syscall_secp256k1_dbl_be(&mut p1);
    let p3 = SyscallPoint256 {
        x: be4([
            5550006413009698729,
            2930477944108794843,
            4206160142528515078,
            11862148329463583523,
        ]),
        y: be4([
            7472242686678486130,
            6550614526735030299,
            16155668332989636091,
            14732040278589264792,
        ]),
    };
    assert_eq!(p1.x, p3.x);
    assert_eq!(p1.y, p3.y);
}
