"""Generate src/vectors.rs for the ed25519 guest.

Usage: python3 scripts/gen_vectors.py src/vectors.rs   (needs the `cryptography` package)

Fixed Ed25519 key and messages msg[i] = (7*i + 3) % 251 (must match `msg()` in main.rs), so the
Ed25519 vectors are reproducible. Also emits one secp256k1 ECDSA signature, used as an accelerated
calibration point; OpenSSL ECDSA is randomized, so that one changes on every run (any valid one works).
"""
import sys
from cryptography.hazmat.primitives.asymmetric import ed25519, ec, utils
from cryptography.hazmat.primitives import hashes, serialization

SIZES = [32, 256, 1232, 4096]


def arr(b):
    return "[" + ",".join(str(x) for x in b) + "]"


out = sys.argv[1]
sk = ed25519.Ed25519PrivateKey.from_private_bytes(bytes(range(32)))
pk = sk.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
lines = [
    "// Generated by scripts/gen_vectors.py, do not edit.",
    f"pub const ED_PK: [u8; 32] = {arr(pk)};",
]
for n in SIZES:
    msg = bytes((i * 7 + 3) % 251 for i in range(n))
    lines.append(f"pub const ED_SIG_{n}: [u8; 64] = {arr(sk.sign(msg))};")

k1 = ec.derive_private_key(0x1234567890ABCDEF, ec.SECP256K1())
z = bytes(range(32))
r, s = utils.decode_dss_signature(k1.sign(z, ec.ECDSA(utils.Prehashed(hashes.SHA256()))))
nums = k1.public_key().public_numbers()
lines.append(f"pub const K1_Z: [u8; 32] = {arr(z)};")
lines.append(f"pub const K1_R: [u8; 32] = {arr(r.to_bytes(32, 'big'))};")
lines.append(f"pub const K1_S: [u8; 32] = {arr(s.to_bytes(32, 'big'))};")
lines.append(f"pub const K1_PKX: [u8; 32] = {arr(nums.x.to_bytes(32, 'big'))};")
lines.append(f"pub const K1_PKY: [u8; 32] = {arr(nums.y.to_bytes(32, 'big'))};")
with open(out, "w") as f:
    f.write("\n".join(lines) + "\n")
