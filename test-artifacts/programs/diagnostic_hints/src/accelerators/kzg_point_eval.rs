use zisk_zkvm_interface::{
    zkvm_kzg_commitment, zkvm_kzg_field_element, zkvm_kzg_point_eval, zkvm_kzg_proof,
    zkvm_status_ZKVM_EOK as ZKVM_EOK,
};

pub fn diagnostic_zkvm_kzg_point_eval() {
    // Trivial instance: polynomial f(x) = 0 evaluated at z = 0 yields y = 0, with both
    // commitment and proof equal to the point at infinity (compressed encoding of ∞ in
    // G1 is 0xc0 followed by 47 zero bytes).
    let mut commitment = zkvm_kzg_commitment { data: [0u8; 48] };
    commitment.data[0] = 0xc0;
    let z = zkvm_kzg_field_element { data: [0u8; 32] };
    let y = zkvm_kzg_field_element { data: [0u8; 32] };
    let mut proof = zkvm_kzg_proof { data: [0u8; 48] };
    proof.data[0] = 0xc0;
    let mut verified = false;
    let status = unsafe { zkvm_kzg_point_eval(&commitment, &z, &y, &proof, &mut verified) };
    assert_eq!(status, ZKVM_EOK);
    assert!(verified);

    // A proof that takes the full pairing check (built from the Ethereum trusted setup's
    // [tau]G1 with py_ecc: proof = [a]G1, commitment = [y]G1 + [a]([tau]G1 - [z]G1)), then the
    // same with y + 1, which must be rejected.
    let commitment = zkvm_kzg_commitment {
        data: [
            0xb9, 0x64, 0xdb, 0xbe, 0x9f, 0xa4, 0x0a, 0x07, 0xc8, 0x47, 0x08, 0x29, 0x7d, 0xc9,
            0xc5, 0x63, 0x00, 0xc1, 0xf2, 0xe8, 0x68, 0xdb, 0x54, 0xce, 0xf9, 0x44, 0x4c, 0xb9,
            0xfc, 0xaf, 0x68, 0xc0, 0xc5, 0xb8, 0x0e, 0x8b, 0xd6, 0xdf, 0x6c, 0xf2, 0xb9, 0x85,
            0x9b, 0xe8, 0x45, 0x47, 0xc1, 0xec,
        ],
    };
    let z = zkvm_kzg_field_element {
        data: [
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
            0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15,
            0x16, 0x17, 0x18, 0x19,
        ],
    };
    let mut y = zkvm_kzg_field_element { data: [0u8; 32] };
    y.data[31] = 0x2a;
    let proof = zkvm_kzg_proof {
        data: [
            0x82, 0x0a, 0xd0, 0xf2, 0x4a, 0x42, 0xc8, 0x21, 0x29, 0xfe, 0xf2, 0xa1, 0x37, 0xf7,
            0xb7, 0xc2, 0x30, 0xc2, 0xaa, 0xff, 0xb7, 0x8f, 0xfd, 0x82, 0xf6, 0xcb, 0xdc, 0xd2,
            0xbf, 0xbf, 0x35, 0x60, 0x43, 0x5a, 0x35, 0xc6, 0x2d, 0x3f, 0xf6, 0x6a, 0xd6, 0x96,
            0xb7, 0x8f, 0x8c, 0x6c, 0x6c, 0x68,
        ],
    };
    let status = unsafe { zkvm_kzg_point_eval(&commitment, &z, &y, &proof, &mut verified) };
    assert_eq!(status, ZKVM_EOK);
    assert!(verified);
    y.data[31] = 0x2b;
    let status = unsafe { zkvm_kzg_point_eval(&commitment, &z, &y, &proof, &mut verified) };
    assert_eq!(status, ZKVM_EOK);
    assert!(!verified);
}
