#!/usr/bin/env python3
"""Write model/zisk_op_attrs.sail: each operation's attributes, from the
`define_ops!` table of core/src/zisk_ops.rs.

What an operation is, besides what it computes: its type, which decides the
state machine that proves it; the bytes of memory it reads and writes as a
precompile, its input and output sizes; and m32, whether the circuit hands
it only the low 32 bits of a, as ZiskInstBuilder sets it: for every
operation whose name contains `_w`. The instruction's is_precompiled and
is_external_op follow from these (zisk_inst_builder.rs).

Usage: gen_op_attrs.py [--check]   (`make constants`; `make ops` checks it)
  --check  fail, writing nothing, if the file is not what it would write
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
OUT = os.path.join(HERE, 'model', 'zisk_op_attrs.sail')


def snake(name):
    return re.sub(r'(?<=[a-z0-9])(?=[A-Z])', '_', name).upper()


def render():
    src = open(os.path.join(ROOT, 'core', 'src', 'zisk_ops.rs')).read()
    types = re.search(r'pub enum OpType \{([^}]*)\}', src).group(1)
    types = re.findall(r'(\w+),', re.sub(r'//[^\n]*', '', types))
    table = src[src.index('define_ops! {', src.index('macro_rules! define_ops') + 1):]
    ops = re.findall(r'\(\w+, "([\w.]+)", (\w+), \w+, 0x[0-9a-fA-F]+, (\d+), (\d+),', table)
    assert len(ops) == len(re.findall(r'\(\w+, "[\w.]+", \w+, \w+, 0x', table)), 'a size is not a literal'

    out = ['''/* Generated by gen_op_attrs.py (`make constants`) from the define_ops!
 * table of core/src/zisk_ops.rs. Do not edit; `make ops` checks it is current.
 *
 * What each operation is, besides what it computes: its type, which decides
 * the state machine that proves it; as a precompile, how many bytes of
 * memory it reads and writes (input_size, output_size); and m32, whether the
 * circuit hands it only the low 32 bits of a — set, as ZiskInstBuilder sets
 * it, for every operation whose name contains `_w`. The model's execution
 * needs only input_size: whether the op gets an extended argument.
 */

enum zisk_op_type = {
''']
    out.append(',\n'.join(f'  OT_{snake(t)}' for t in types))
    out.append('''
}

struct zisk_op_attrs = {
  op_type     : zisk_op_type,
  input_size  : int,
  output_size : int,
  m32         : bool
}

val zisk_op_attrs : zisk_op -> zisk_op_attrs
function zisk_op_attrs(op) = match op {
''')
    rows = []
    for name, ty, insz, outsz in ops:
        assert ty in types, ty
        m32 = 'true' if '_w' in name else 'false'
        rows.append(f'  ZOP_{name.upper()}() => struct {{ op_type = OT_{snake(ty)}, '
                    f'input_size = {insz}, output_size = {outsz}, m32 = {m32} }}')
    out.append(',\n'.join(rows))
    out.append('''
}

/* An instruction's is_precompiled: its op reads memory as a precompile. */
val zisk_op_is_precompiled : zisk_op -> bool
function zisk_op_is_precompiled(op) = zisk_op_attrs(op).input_size > 0

/* An instruction's is_external_op: a state machine other than Main proves
 * its op. */
val zisk_op_is_external : zisk_op -> bool
function zisk_op_is_external(op) = match zisk_op_attrs(op).op_type {
  OT_INTERNAL => false,
  OT_FCALL    => false,
  _           => true
}
''')
    return ''.join(out), len(ops)


def main():
    text, n = render()
    if '--check' in sys.argv:
        if not os.path.exists(OUT) or open(OUT).read() != text:
            sys.exit(f'FAIL: {os.path.relpath(OUT)} is stale: core/src/zisk_ops.rs changed; run `make constants`')
        print(f'OK: {os.path.relpath(OUT)} has every operation\'s attributes, as zisk_ops.rs gives them.')
        return
    open(OUT, 'w').write(text)
    print(f'wrote {os.path.relpath(OUT)}: the attributes of {n} operations')


if __name__ == '__main__':
    main()
