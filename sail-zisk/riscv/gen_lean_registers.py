#!/usr/bin/env python3
"""Write lean/ZiskRiscvRun/Registers.lean: sail-riscv's register
initialisation, for the executable model in ZisK's profile.

sail-riscv's Lean emulator (lean_emulator/LeanRiscv.lean) gives every
register a value before a run — Lean's register map throws on a register
nobody wrote — in `initializeRegisters`. This takes those `writeReg` lines
unchanged, renaming the model's module (LeanRV64DExecutable, the default
configuration's, to LeanZiskRVExecutable, ZisK's profile's), and keeps
those of the registers the model has — the executable model is built from
the modules ZisK's profile needs, not all of them. It leaves out the HTIF
set-up before them, which needs a `.tohost` section a ZisK guest has no
reason to have.

Usage: gen_lean_registers.py <sail-riscv checkout> <model's Defs.lean> <out.lean>
    (`make riscv-run`)
"""

import re
import sys


def main():
    src = open(f'{sys.argv[1]}/lean_emulator/LeanRiscv.lean').read()
    body = src[src.index('def initializeRegisters'):src.index('def my_main')]
    lines = [l for l in body.splitlines() if re.match(r'\s+writeReg \w+ \(← \(undefined_', l)]
    assert len(lines) > 100, 'initializeRegisters no longer looks as expected'
    defs = open(sys.argv[2]).read()
    regs = defs[defs.index('inductive Register : Type where'):]
    regs = set(re.findall(r'^  \| (\w+)$', regs[:regs.index('deriving')], re.M))
    lines = [l for l in lines if re.match(r'\s+writeReg (\w+)', l).group(1) in regs]
    out = ['''/-
  Generated by riscv/gen_lean_registers.py from sail-riscv's
  lean_emulator/LeanRiscv.lean (`initializeRegisters`). Do not edit.

  Every register of the model gets a value, as sail-riscv's Lean emulator
  gives it before a run.
-/
import LeanZiskRVExecutable

namespace ZiskRiscvRun

open LeanZiskRVExecutable
open LeanZiskRVExecutable.Functions
open Register
open Sail

set_option maxRecDepth 2000000

def initializeRegisters : SailM PUnit := do
''']
    out += [l.rstrip() + '\n' for l in lines]
    out.append('\nend ZiskRiscvRun\n')
    open(sys.argv[3], 'w').write(''.join(out))
    print(f'wrote {sys.argv[3]}: {len(lines)} registers of the model\'s {len(regs)}')


if __name__ == '__main__':
    main()
