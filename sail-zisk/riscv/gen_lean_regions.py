#!/usr/bin/env python3
"""Write lean/Equiv/Regions.lean: sail-riscv's PMA regions in ZisK's
profile, as the model's initialisation writes them.

sail-riscv's Lean (`sail_model_init`, in LeanZiskRV.lean) writes the
`pma_regions` register from the configuration — ZisK's memory map, the
input, the ROM and the RAM (riscv/zisk_profile.py) — as a literal list.
This takes that literal unchanged, as `ziskRegions`, so that the proofs can
state their regions as the ones a run of the model has.

Usage: gen_lean_regions.py <LeanZiskRV.lean> <out.lean>    (`make riscv`)
"""

import sys


def main():
    src = open(sys.argv[1]).read()
    # The names the literal uses (IOMemory, AccessFault, ...), as the model's
    # file opens them.
    opens = '\n'.join(l for l in src[:src.index('def sail_model_init')].splitlines() if l.startswith('open '))
    body = src[src.index('def sail_model_init'):]
    start = body.index('writeReg pma_regions ') + len('writeReg pma_regions ')
    depth, end = 0, None
    for i, c in enumerate(body[start:], start):
        if c == '[':
            depth += 1
        elif c == ']':
            depth -= 1
            if depth == 0:
                end = i + 1
                break
    assert end is not None, 'sail_model_init no longer writes pma_regions as expected'
    lines = body[start:end].splitlines()
    # Move the literal to column 2 under the definition, every line by the
    # same amount: its layout is significant.
    col = start - (body.rindex('\n', 0, start) + 1)
    shift = col - 2
    assert all(l[:shift].strip() == '' for l in lines[1:]), 'unexpected layout'
    lit = '\n'.join(['  ' + lines[0]] + [l[shift:] for l in lines[1:]])
    out = f'''/-
  Generated by riscv/gen_lean_regions.py from sail-riscv's Lean in ZisK's
  profile (LeanZiskRV.lean, `sail_model_init`). Do not edit.

  The PMA regions the model's initialisation writes: ZisK's memory map —
  the input, the ROM and the RAM (riscv/zisk_profile.py).
-/
import LeanZiskRV

namespace LeanZiskRV

{opens}

set_option maxRecDepth 100000

def _root_.Equiv.ziskRegions : List PMA_Region :=
{lit}

end LeanZiskRV
'''
    open(sys.argv[2], 'w').write(out)


if __name__ == '__main__':
    main()
