#!/usr/bin/env python3
"""Write doc/ops.md: every ZisK operation, and where the model stands on it.

Reads the `define_ops!` table of core/src/zisk_ops.rs, searches the RISC-V
transpiler's source (transpilers/riscv) for each mnemonic — so whether the
transpiler emits an operation is approximate — and the model's operations
(the `ZOP_<OP>` constructors of model/zisk_insts_*.sail).

Usage: gen_ops_doc.py   (`make opsdoc`)
"""

import glob
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..')


def main():
    src = open(os.path.join(ROOT, 'core', 'src', 'zisk_ops.rs')).read()
    table = src[src.index('define_ops! {', src.index('macro_rules! define_ops') + 1):]
    ops = re.findall(r'\((\w+), "([\w.]+)", (\w+), \w+, (0x[0-9a-fA-F]+),', table)
    tr = ''.join(open(f).read() for f in glob.glob(os.path.join(ROOT, 'transpilers', 'riscv', 'src', '*.rs')))
    model = ''.join(open(f).read() for f in glob.glob(os.path.join(HERE, '..', 'model', 'zisk_insts_*.sail')))
    have = set(re.findall(r'union clause zisk_op = (ZOP_\w+)', model))
    rows = [(mn, ty, code, re.search(r'"%s"' % re.escape(mn), tr) is not None, 'ZOP_' + mn.upper() in have)
            for _, mn, ty, code in ops]
    out = [f'''# ZisK operations: coverage

Generated by `doc/gen_ops_doc.py` (`make opsdoc`). Do not edit.

Every operation of `ZiskOp` (`core/src/zisk_ops.rs`, the `define_ops!` table),
by type, with whether the RISC-V transpiler (`transpilers/riscv`) emits it —
by a search for its mnemonic in the transpiler's source, so approximate — and
whether the model specifies it. The equivalence with sail-riscv needs the ones
the transpiler emits.

{len(rows)} operations; the transpiler emits {sum(r[3] for r in rows)}; the model specifies {sum(r[4] for r in rows)}.
''']
    by_type = {}
    for r in rows:
        by_type.setdefault(r[1], []).append(r)
    for ty, rs in by_type.items():
        done = sum(r[4] for r in rs)
        out.append(f'\n## {ty} ({done} of {len(rs)})\n\n| op | opcode | emitted by riscv2zisk | in the model |\n|---|---|---|---|')
        for mn, _, code, em, im in rs:
            out.append(f'| `{mn}` | {code} | {"yes" if em else "—"} | {"yes" if im else "—"} |')
    open(os.path.join(HERE, 'ops.md'), 'w').write('\n'.join(out) + '\n')
    print(f'doc/ops.md: {len(rows)} operations, {sum(r[4] for r in rows)} in the model')


if __name__ == '__main__':
    main()
