#!/usr/bin/env python3
"""Turn the emulator's op test vectors into Sail checks.

Reads the vectors `sail-difftest ops` writes (`<op> <a> <b> <c> <flag>`, with
`(c, flag)` what ZisK's own op functions return), and writes a Sail file
defining `op_checks`, which compares the model's `zisk_exec` with them for
every operation the model specifies (a `ZOP_<OP>` constructor in
model/zisk_insts_*.sail). Prints the operations it tested and the ones the
model does not have yet.

Usage: gen_op_checks.py <vectors> <out.sail>
"""

import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def model_ops():
    src = ''.join(open(f).read() for f in glob.glob(os.path.join(HERE, '..', 'model', 'zisk_insts_*.sail')))
    return set(re.findall(r'union clause zisk_op = (ZOP_\w+)', src))


def main():
    vectors, out = sys.argv[1], sys.argv[2]
    have = model_ops()
    tested, missing, checks = set(), set(), []
    for line in open(vectors):
        name, a, b, c, flag = line.split()
        ctor = 'ZOP_' + name.upper()
        if ctor not in have:
            missing.add(name)
            continue
        tested.add(name)
        checks.append(f'  n = n + check_op("{name}", {ctor}(), {a}, {b}, {c}, {"true" if flag == "1" else "false"});')
    # One function per 2000 checks keeps the C compiler's work per function small.
    chunks = [checks[i:i + 2000] for i in range(0, len(checks), 2000)] or [[]]
    with open(out, 'w') as f:
        f.write('/* Generated by test/gen_op_checks.py from `sail-difftest ops`. Do not edit. */\n\n')
        for k, chunk in enumerate(chunks):
            f.write(f'val op_checks_{k} : unit -> int\nfunction op_checks_{k}() = {{\n  var n : int = 0;\n')
            f.write('\n'.join(chunk) + '\n  n\n}\n\n')
        f.write('val op_checks : unit -> int\nfunction op_checks() = ' +
                ' + '.join(f'op_checks_{k}()' for k in range(len(chunks))) + '\n')
    print(f'{len(checks)} checks for {len(tested)} operations: {" ".join(sorted(tested))}')
    print(f'{len(missing)} operations the model does not specify yet: {" ".join(sorted(missing))}')


if __name__ == '__main__':
    main()
