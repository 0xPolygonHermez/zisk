import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { verify, getCurve, computeQ, openingEvaluations } from '../.cache/proofman-pilfflonk-1.4.0-alpha/js/src/verify.js';
import { fromObjectVk } from '../.cache/proofman-pilfflonk-1.4.0-alpha/js/src/vkey.js';
import { fromObjectProof, fromObjectPublics } from '../.cache/proofman-pilfflonk-1.4.0-alpha/js/src/proof.js';
import { computeChallenges } from '../.cache/proofman-pilfflonk-1.4.0-alpha/js/src/challenges.js';
import { computeRoots, computeZerofiers, computeR, computeQuotients, computeF, computeE, computeJ } from '../.cache/proofman-pilfflonk-1.4.0-alpha/js/src/shplonk.js';

const fixture = JSON.parse(readFileSync(new URL('../fixtures/blake3.json', import.meta.url)));
const key = JSON.parse(readFileSync(new URL('../fixtures/vkey.json', import.meta.url)));
assert.equal(key.digest, '0xe9eb2c78fc2cff7c38c459927e3afd00189a06af869a597c8109240ab0aedd3a');
const curve = await getCurve();
const vk = fromObjectVk(curve, key);
const raw = Buffer.from(fixture.proofBytes.slice(2), 'hex');
let at = 0;
const word = () => { const v = BigInt('0x' + raw.subarray(at, at + 32).toString('hex')); at += 32; return v.toString(); };
const object = { protocol: 'pilfflonk', curve: 'bn128', polynomials: {}, evaluations: {} };
for (const name of [...vk.commitmentNames, 'W', 'Wp']) object.polynomials[name] = [word(), word(), '1'];
for (const i of vk.evaluationOrder) object.evaluations[vk.evMap[i].name] = word();
for (const name of [...vk.qPieceNames, 'inv', 'invZh']) object.evaluations[name] = word();
assert.equal(at, raw.length);
const preimage = Buffer.concat(['programVK','publicValues','rootCVadcopFinal'].map(n => Buffer.from(fixture[n].slice(2), 'hex')));
const digest = BigInt('0x' + createHash('sha256').update(preimage).digest('hex')) % curve.r;
const publicsObject = [digest.toString()];
assert.equal(await verify(key, publicsObject, object), true, 'reference must accept the real proof');
assert.equal(await verify(key, [(digest ^ 1n).toString()], object), false, 'reference must reject a changed statement');
const changed = structuredClone(object);
changed.evaluations.inv = (BigInt(changed.evaluations.inv) ^ 1n).toString();
assert.equal(await verify(key, publicsObject, changed), false, 'reference must reject a changed inverse');
const proof = fromObjectProof(curve, object, vk);
const publics = fromObjectPublics(curve, publicsObject, vk);
const ch = computeChallenges(curve, vk, publics, proof);
const shape = { nBits: vk.power, powerW: vk.powerW, f: vk.layout };
const { xi, f: roots } = computeRoots(curve, shape, ch.xiSeed);
const { q } = computeQ(curve, vk, publics, proof, ch, xi);
const z = computeZerofiers(curve, roots, ch.y);
const r = computeR(curve, vk.layout, roots, openingEvaluations(vk, proof, q), z, ch.y);
const quotients = computeQuotients(curve, z, ch.alpha);
const F = computeF(curve, [...vk.fixedCommitments, ...proof.commitments], quotients);
const E = computeE(curve, r, quotients);
const J = computeJ(curve, proof.W, quotients[0]);
const scalar = x => curve.Fr.toObject(x).toString();
const point = p => curve.G1.toObject(curve.G1.toAffine(p)).slice(0, 2).map(String);
const trace = { digest: digest.toString(), challenges: [ch.stages[2][0], ch.stages[2][1], ch.stdVc, ch.xiSeed, ch.alpha, ch.y].map(scalar), xi: scalar(xi), q: scalar(q), r: r.map(scalar), quotients: quotients.map(scalar), F: point(F), E: point(E), J: point(J) };
for (const [name, value] of Object.entries({ proof: object, publics: publicsObject, trace }))
  writeFileSync(new URL(`../fixtures/${name}.json`, import.meta.url), JSON.stringify(value, null, 2) + '\n');
console.log('Release JS oracle: valid accepted; changed statement and inverse rejected; intermediate trace saved.');
