#!/usr/bin/env python3
"""Regenerate u256_semantics_guest.c.

The expected values in that guest are golden vectors, and they are produced HERE --
by an independent model of the EVM semantics -- rather than captured from the ziskasm
backend under test. That is the whole point: a vector recorded from the implementation
would agree with any bug it has. See the golden-vector warning in ziskasm/zisklib.md.

To add a case, extend the tables at the bottom and re-run:

    python3 u256_semantics_gen.py && git diff u256_semantics_guest.c
"""
import pathlib

M = 1 << 256


def to_signed(x):
    return x - M if x >> 255 else x


def to_unsigned(x):
    return x % M


def sdiv(a, b):
    """EVM SDIV: truncated toward zero; x/0 = 0; -2^255 / -1 wraps to -2^255."""
    if b == 0:
        return 0
    sa, sb = to_signed(a), to_signed(b)
    q = abs(sa) // abs(sb)
    if (sa < 0) != (sb < 0):
        q = -q
    return to_unsigned(q)


def smod(a, b):
    """EVM SMOD: the remainder takes the sign of the DIVIDEND; x%0 = 0."""
    if b == 0:
        return 0
    sa, sb = to_signed(a), to_signed(b)
    r = abs(sa) % abs(sb)
    return to_unsigned(-r if sa < 0 else r)


def sar(shift, value):
    """EVM SAR: arithmetic shift; shift >= 256 saturates to 0 (a >= 0) or -1 (a < 0)."""
    sv = to_signed(value)
    if shift >= 256:
        return to_unsigned(-1 if sv < 0 else 0)
    return to_unsigned(sv >> shift)  # Python >> is arithmetic on negatives


def signextend(b, x):
    """EVM SIGNEXTEND: sign-extend x from byte b (0 = least significant); b >= 31 is a no-op."""
    if b >= 31:
        return x
    bit = b * 8 + 7
    mask = (1 << (bit + 1)) - 1
    return to_unsigned(x | ~mask) if (x >> bit) & 1 else x & mask


def slt(a, b):
    return 1 if to_signed(a) < to_signed(b) else 0


def sgt(a, b):
    return 1 if to_signed(a) > to_signed(b) else 0


NEG1, NEG2, NEG7, NEG8 = M - 1, M - 2, M - 7, M - 8
MINNEG = 1 << 255          # -2^255
MAXPOS = MINNEG - 1        #  2^255-1

CMP = [(NEG2, NEG1, "-2", "-1"), (NEG1, NEG2, "-1", "-2"), (NEG1, NEG1, "-1", "-1"),
       (NEG1, 1, "-1", "1"), (1, NEG1, "1", "-1"), (0, NEG1, "0", "-1"),
       (NEG1, 0, "-1", "0"), (1, 2, "1", "2"),
       (MINNEG, MAXPOS, "-2^255", "2^255-1"), (MAXPOS, MINNEG, "2^255-1", "-2^255")]
SDIV = [(7, 2, "7", "2"), (NEG7, 2, "-7", "2"), (7, NEG2, "7", "-2"),
        (NEG7, NEG2, "-7", "-2"), (MINNEG, NEG1, "-2^255", "-1"), (5, 0, "5", "0")]
SMOD = [(7, 2, "7", "2"), (NEG7, 2, "-7", "2"), (7, NEG2, "7", "-2"),
        (NEG7, NEG2, "-7", "-2"), (5, 0, "5", "0")]
SAR = [(1, NEG8, "1", "-8"), (255, NEG1, "255", "-1"), (256, NEG1, "256", "-1"),
       (1, 8, "1", "8"), (256, 8, "256", "8")]
SEXT = [(0, 0xFF, "0", "0xff"), (0, 0x7F, "0", "0x7f"), (1, 0xFFFF, "1", "0xffff"),
        (31, 0xDEAD, "31", "0xdead"), (32, 0xFF, "32", "0xff")]


def build():
    cases = []
    for a, b, la, lb in CMP:
        cases.append(("slt", a, b, slt(a, b), f"slt({la},{lb})"))
        cases.append(("sgt", a, b, sgt(a, b), f"sgt({la},{lb})"))
    for tbl, name, fn in ((SDIV, "sdiv", sdiv), (SMOD, "smod", smod),
                          (SAR, "sar", sar), (SEXT, "signextend", signextend)):
        for a, b, la, lb in tbl:
            cases.append((name, a, b, fn(a, b), f"{name}({la},{lb})"))
    return cases


def be(x):
    return ",".join(f"0x{c:02x}" for c in x.to_bytes(32, "big"))


HEADER = '''/*
 * u256_semantics_guest.c - EVM signed/sign-sensitive semantics for the EF U256 ABI.
 *
 * GENERATED by u256_semantics_gen.py -- edit that, not this file.
 *
 * Covers the operations whose results depend on two's-complement sign handling, which
 * the aliasing guest does not check: slt, sgt, sdiv, smod, sar and signextend. These
 * are the easiest to get subtly wrong (truncate-toward-zero vs floor, sign of the
 * modulo, the -2^255 / -1 overflow, arithmetic vs logical shift, saturating shift
 * counts), and they had no standing coverage.
 *
 * Expected values are golden vectors produced by an INDEPENDENT model of the EVM
 * semantics, not transcribed from this backend -- so the test cannot agree with a bug
 * by construction.
 *
 * Self-checking, like u256_alias_guest.c: one byte per case, 00 = pass, 01 = FAIL
 * (wrong value or a non-EOK status), then the 01 00 negative control. Expected output
 * is therefore all zeros followed by 0100.
 *
 * Build/run: see README.md ("U256 signed semantics").
 */
#include "zkvm_u256.h"

typedef zkvm_status (*bin_t)(const zkvm_u256 *, const zkvm_u256 *, zkvm_u256 *);
typedef struct { bin_t fn; zkvm_u256 a, b, want; } case_t;

/* Generated golden vectors (see header): { op, a, b, expected } */
static const case_t CASES[] = {
'''

FOOTER = '''};

static zkvm_u256 got;
static volatile uint8_t *O;
static unsigned k;
static int ne(const zkvm_u256 *x, const zkvm_u256 *y){
  for (int i = 0; i < 32; i++) if (x->data[i] != y->data[i]) return 1;
  return 0;
}
static void rec(int bad){ O[k++] = bad ? 0x01 : 0x00; }

static uint8_t g_bss[32];
static volatile uint32_t g_data = 0x600df00d;
int main(void){
  __asm__ volatile("" : : "r"(&g_bss[0]), "r"(&g_data) : "memory");
  O = (volatile uint8_t *)(0xA0410000ULL); k = 0;

  for (unsigned i = 0; i < sizeof(CASES)/sizeof(CASES[0]); i++) {
    const case_t *c = &CASES[i];
    zkvm_status s = c->fn(&c->a, &c->b, &got);
    rec(s != ZKVM_EOK || ne(&got, &c->want));
  }

  /* Negative control: prove the comparison machinery fires. Expect 01 then 00. */
  rec(ne(&CASES[0].a, &CASES[0].b));
  rec(ne(&CASES[0].a, &CASES[0].a));
  return 0;
}
'''

if __name__ == "__main__":
    rows = [
        f"  {{ zkvm_u256_{op}, {{{{{be(a)}}}}}, {{{{{be(b)}}}}}, {{{{{be(r)}}}}}, }}, /* {label} */"
        for op, a, b, r, label in build()
    ]
    out = pathlib.Path(__file__).with_name("u256_semantics_guest.c")
    out.write_text(HEADER + "\n".join(rows) + "\n" + FOOTER)
    print(f"wrote {out.name}: {len(rows)} cases")
